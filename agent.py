"""Session handling and the detect -> extract -> engage pipeline."""
import logging
import time
import uuid
from collections import OrderedDict

import detection
import extraction
import llm

log = logging.getLogger("honeypot.agent")

SCAM_THRESHOLD = 50
MAX_SESSIONS = 500
MAX_HISTORY = 30

_sessions: "OrderedDict[str, dict]" = OrderedDict()


def _new_session(sid: str) -> dict:
    return {
        "session_id": sid,
        "created": time.time(),
        "history": [],        # {"role": "user"|"assistant", "content": str}
        "timeline": [],       # human-readable events for the report
        "turns": 0,
        "risk_score": 0,
        "scam_type": "Not a clear scam",
        "indicators": [],
        "explanation": "",
        "intel": extraction.empty(),
        "mode": "",
    }


def get_session(sid: str | None) -> dict:
    if not sid or sid not in _sessions:
        sid = sid if sid and len(sid) <= 64 else uuid.uuid4().hex
        _sessions[sid] = _new_session(sid)
        while len(_sessions) > MAX_SESSIONS:
            _sessions.popitem(last=False)
    _sessions.move_to_end(sid)
    return _sessions[sid]


def find_session(sid: str):
    return _sessions.get(sid)


def reset_all():  # used by tests
    _sessions.clear()


def status() -> dict:
    if llm.is_configured():
        return {"mode": "llm", "label": f"Meta Model API ({llm.model_name()})"}
    return {"mode": "rule-based", "label": "Rule-based demo mode (no API key set)"}


def _analyse(message: str):
    """Return (detection dict, mode string). Falls back if the LLM fails."""
    if llm.is_configured():
        try:
            return llm.detect(message), "llm"
        except Exception as exc:  # network, auth, bad JSON, rate limit...
            log.warning("LLM detect failed (%s); using rule-based fallback",
                        type(exc).__name__)
    return detection.analyze(message), "rule-based"


def _reply(session: dict, mode: str) -> tuple[str, str]:
    if mode == "llm" and llm.is_configured():
        try:
            return llm.agent_reply(session["history"]), "llm"
        except Exception as exc:
            log.warning("LLM reply failed (%s); using canned reply",
                        type(exc).__name__)
    return detection.fallback_reply(session["turns"]), "rule-based"


def handle(session_id: str | None, message: str) -> dict:
    s = get_session(session_id)
    message = message.strip()
    s["turns"] += 1
    s["history"].append({"role": "user", "content": message})

    det, mode = _analyse(message)
    s["mode"] = mode
    # Risk never drops mid-conversation: a scammer can be polite later.
    if det["risk_score"] >= s["risk_score"]:
        s["risk_score"] = det["risk_score"]
        s["scam_type"] = det["scam_type"]
        s["explanation"] = det["explanation"]
    s["indicators"] = extraction._dedupe(s["indicators"] + det["indicators"])

    found = extraction.extract(message)
    s["intel"] = extraction.merge(s["intel"], found)
    s["timeline"].append({
        "turn": s["turns"], "event": "message_received",
        "risk_score": det["risk_score"],
        "found": {k: len(v) for k, v in found.items() if v},
    })

    is_scam = s["risk_score"] >= SCAM_THRESHOLD
    reply = None
    if is_scam:
        reply, reply_mode = _reply(s, mode)
        s["history"].append({"role": "assistant", "content": reply})
        s["history"] = s["history"][-MAX_HISTORY:]
        s["timeline"].append({"turn": s["turns"], "event": "agent_replied",
                              "source": reply_mode})

    log.info("session=%s turn=%d risk=%d mode=%s extracted=%s",
             s["session_id"][:8], s["turns"], s["risk_score"], mode,
             {k: [extraction.mask(x) for x in v]
              for k, v in found.items() if v})

    return {
        "session_id": s["session_id"],
        "scam_detected": is_scam,
        "engagement_status": "agent_active" if is_scam else "ignored",
        "conversation_turns": s["turns"],
        "risk_score": s["risk_score"],
        "scam_type": s["scam_type"],
        "indicators": s["indicators"],
        "explanation": s["explanation"],
        "agent_reply": reply,
        "analysis_mode": mode,
        "extracted_intelligence": s["intel"],
    }


def build_report(sid: str) -> dict | None:
    s = find_session(sid)
    if not s:
        return None
    return {
        "report_generated_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "session_id": s["session_id"],
        "turns": s["turns"],
        "risk_score": s["risk_score"],
        "scam_type": s["scam_type"],
        "indicators": s["indicators"],
        "extracted_intelligence": s["intel"],
        "conversation": s["history"],
        "timeline": s["timeline"],
        "analysis_mode": s["mode"],
        "note": ("Generated by an automated tool. Review manually before "
                 "reporting to cybercrime.gov.in or your bank."),
    }
